    private final EquipmentMapper equipmentMapper;
    private final EquipmentManualMapper manualMapper;

    /** 启动时批量补齐所有缺少正文的设备手册 */
    @Override
    public void run(ApplicationArguments args) {
        int filled = fillMissing();
        if (filled > 0) {
            log.info("设备手册预置完成：补全 {} 台设备的操作文档与安全注意事项", filled);
        }
    }

    /** 为所有缺少操作文档的设备补齐预置内容，返回补齐数量 */
    @Transactional
    public int fillMissing() {
        int filled = 0;
        for (Equipment e : equipmentMapper.selectList(null)) {
            if (fillIfMissing(e)) filled++;
        }
        return filled;
    }

    /** 单台设备补齐：已有正文则跳过，避免覆盖人工编辑内容 */
    @Transactional
    public boolean fillIfMissing(Equipment equipment) {
        if (equipment == null || equipment.getId() == null) return false;
        EquipmentManual manual = manualMapper.selectOne(new LambdaQueryWrapper<EquipmentManual>()
                .eq(EquipmentManual::getEquipmentId, equipment.getId()));
        if (manual != null && StringUtils.hasText(manual.getContent())) return false;

        String[] template = templateOf(equipment);
        if (manual == null) {
            manual = new EquipmentManual();
            manual.setEquipmentId(equipment.getId());
        }
        manual.setContent(template[0]);
        manual.setSafetyNotes(template[1]);
        manual.setEditorName(SEED_EDITOR);
        manual.setUpdateTime(LocalDateTime.now());
        if (manual.getId() == null) {
            manualMapper.insert(manual);
        } else {
            manualMapper.updateById(manual);
        }
        return true;
    }

    /** 匹配模板：设备名 → 分类 → 通用（通用模板会带上设备名，保证内容贴合） */
    private String[] templateOf(Equipment equipment) {
        String[] byName = TEMPLATES.get(equipment.getName());
        if (byName != null) return byName;
        String[] byCategory = CATEGORY_TEMPLATES.get(equipment.getCategory());
        if (byCategory != null) return byCategory;
        return new String[]{
                "1. 使用前确认「" + equipment.getName() + "」处于可用状态，电源、线缆与附件完整；\n"
                        + "2. 按设备面板或软件提示设置实验参数，先空载确认运行正常；\n"
                        + "3. 使用中注意观察运行状态，出现异常立即停机断电并上报；\n"
                        + "4. 使用结束恢复初始状态，清洁设备并填写使用记录。",
                "· 使用前须阅读说明并经培训，禁止违规操作；\n"
                        + "· 设备运行中不得离人，异响、异味立即断电；\n"
                        + "· 保持设备周围通道畅通，禁止堆放杂物与易燃品。"};
    }
